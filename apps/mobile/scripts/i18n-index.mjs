// Writes src/i18n/resources.ts: static requires for every src/i18n/locales/<lang>/<ns>.json
// (Metro can't import a folder dynamically). Run after adding a language or section:
//   node scripts/i18n-index.mjs
import { readdirSync, writeFileSync, existsSync } from "node:fs";

const root = "src/i18n/locales";
const langs = readdirSync(root).filter((d) => !d.startsWith(".")).sort();
const lines = ["// Generated by scripts/i18n-index.mjs — do not edit by hand.", "export const resources = {"];
for (const lang of langs) {
  const files = readdirSync(`${root}/${lang}`).filter((f) => f.endsWith(".json")).sort();
  lines.push(`  ${JSON.stringify(lang)}: {`);
  for (const f of files) lines.push(`    ${JSON.stringify(f.replace(/\.json$/, ""))}: require("./locales/${lang}/${f}"),`);
  lines.push("  },");
}
lines.push("} as const;", "");
writeFileSync("src/i18n/resources.ts", lines.join("\n"));
console.log(`resources.ts: ${langs.length} languages`, existsSync(`${root}/en`) ? "" : "(no en!)");
